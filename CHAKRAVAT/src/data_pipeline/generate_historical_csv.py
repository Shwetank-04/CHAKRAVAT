FIELDNAMES = [
    "record_id",
    "storm_id",
    "storm_name",
    "iso_time",
    "basin",
    "latitude",
    "longitude",
    "wind_speed_kts",
    "wind_speed_kmh",
    "central_pressure_hpa",
    "pressure_drop_hpa",
    "nature_code",
    "imd_category",
    "translation_speed_kts",
    "translation_heading_deg",
    "is_landfall",
    "data_source",
    "quality_flag",
]

def generate_csv(target_path: str):
    os.makedirs(os.path.dirname(target_path), exist_ok=True)
    rows = []
    global_idx = 1

    for storm_id, storm_name, basin, nature_code, fixes in STORMS:
        for local_idx, fix in enumerate(fixes, start=1):
            iso_time, lat, lon, wind_kts, pres_hpa, cat, spd_kts, hdg_deg, landfall = fix
            wind_kmh = round(wind_kts * 1.852, 1)
            drop_hpa = round(1010.0 - pres_hpa, 1)
            record_id = f"{storm_name}_{iso_time[:4]}_{local_idx:03d}"

            row = {
                "record_id": record_id,
                "storm_id": storm_id,
                "storm_name": storm_name,
                "iso_time": iso_time,
                "basin": basin,
                "latitude": lat,
                "longitude": lon,
                "wind_speed_kts": wind_kts,
                "wind_speed_kmh": wind_kmh,
                "central_pressure_hpa": pres_hpa,
                "pressure_drop_hpa": drop_hpa,
                "nature_code": nature_code,
                "imd_category": cat,
                "translation_speed_kts": spd_kts,
                "translation_heading_deg": hdg_deg,
                "is_landfall": landfall,
                "data_source": "IBTrACS v04r00 / IMD RSMC New Delhi",
                "quality_flag": 0,
            }
            rows.append(row)
            global_idx += 1

    with open(target_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Generated {len(rows)} records in {target_path}")
    return len(rows)

if __name__ == "__main__":
    out_path = os.path.join("data", "bundled", "historical_cyclones.csv")
    generate_csv(out_path)
